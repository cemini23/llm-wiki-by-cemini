#!/usr/bin/env bash
# G0: wire discord-ops MCP for youratto + OSINT (macOS).
# Secrets stay in User env / shell — never commit tokens.
#
# Usage:
#   bash scripts/setup_discord_ops_macos.sh
#   YOURATTO_DISCORD_BOT_TOKEN=… YOURATTO_DISCORD_GUILD_ID=… bash scripts/setup_discord_ops_macos.sh --non-interactive
#
# TipDrop (David) used the Windows twin:
#   tipdrop-workspace-kit/scripts/setup-discord-agent-ops.ps1
# Tool: https://github.com/bookedsolidtech/discord-ops (MIT)

set -euo pipefail

OSINT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ATTO_ROOT="${ATTO_ROOT:-/Users/claudiobarone/Projects/atto}"
NONINTERACTIVE=0
[[ "${1:-}" == "--non-interactive" ]] && NONINTERACTIVE=1

DISCORD_OPS_TOOLS="create_channel,delete_channel,edit_channel,get_channel,list_channels,set_slowmode,create_webhook,delete_webhook,edit_webhook,execute_webhook,get_webhook,list_webhooks,health_check,list_guilds,get_guild,assign_role,list_members,list_roles,create_invite,get_invites,send_message"

echo "=== discord-ops setup (youratto + OSINT) ==="

if ! command -v node >/dev/null 2>&1; then
  echo "Need Node.js 20+ on PATH" >&2
  exit 1
fi
echo "Node: $(node -v)"

prompt() {
  local var="$1" hint="$2"
  if [[ -n "${!var:-}" ]]; then
    return 0
  fi
  if [[ "$NONINTERACTIVE" -eq 1 ]]; then
    return 0
  fi
  echo ""
  echo "$hint"
  # shellcheck disable=SC2162
  read -r -s -p "Value (hidden for tokens; visible for IDs if short): " val
  # For guild IDs we want visible — if var ends in TOKEN use silent
  if [[ "$var" == *TOKEN* ]]; then
    echo
    printf -v "$var" '%s' "$val"
  else
    # re-prompt visible for IDs
    echo
    read -r -p "Paste again (visible): " val
    printf -v "$var" '%s' "$val"
  fi
}

# Prefer dedicated youratto token; fall back to TipDrop-style DISCORD_BOT_TOKEN only if set
YOURATTO_DISCORD_BOT_TOKEN="${YOURATTO_DISCORD_BOT_TOKEN:-}"
YOURATTO_DISCORD_GUILD_ID="${YOURATTO_DISCORD_GUILD_ID:-}"
OSINT_DISCORD_BOT_TOKEN="${OSINT_DISCORD_BOT_TOKEN:-${YOURATTO_DISCORD_BOT_TOKEN}}"
OSINT_DISCORD_GUILD_ID="${OSINT_DISCORD_GUILD_ID:-}"

if [[ -z "$YOURATTO_DISCORD_BOT_TOKEN" && -n "${DISCORD_BOT_TOKEN:-}" ]]; then
  echo "Note: using DISCORD_BOT_TOKEN as YOURATTO_DISCORD_BOT_TOKEN (shared bot)."
  YOURATTO_DISCORD_BOT_TOKEN="$DISCORD_BOT_TOKEN"
  OSINT_DISCORD_BOT_TOKEN="${OSINT_DISCORD_BOT_TOKEN:-$DISCORD_BOT_TOKEN}"
fi

if [[ "$NONINTERACTIVE" -eq 0 ]]; then
  if [[ -z "$YOURATTO_DISCORD_BOT_TOKEN" ]]; then
    echo ""
    echo "Discord Developer Portal → New Application → Bot → Reset Token"
    echo "https://discord.com/developers/applications"
    read -r -s -p "Paste YOURATTO bot token: " YOURATTO_DISCORD_BOT_TOKEN
    echo
  fi
  if [[ -z "$YOURATTO_DISCORD_GUILD_ID" ]]; then
    echo "Enable Developer Mode → right-click youratto Discord server → Copy Server ID"
    read -r -p "Paste YOURATTO guild ID: " YOURATTO_DISCORD_GUILD_ID
  fi
  if [[ -z "$OSINT_DISCORD_GUILD_ID" ]]; then
    echo "Optional: separate OSINT/Cemini ops guild (Enter = same as youratto)"
    read -r -p "Paste OSINT guild ID or Enter: " OSINT_DISCORD_GUILD_ID
    OSINT_DISCORD_GUILD_ID="${OSINT_DISCORD_GUILD_ID:-$YOURATTO_DISCORD_GUILD_ID}"
  fi
  OSINT_DISCORD_BOT_TOKEN="${OSINT_DISCORD_BOT_TOKEN:-$YOURATTO_DISCORD_BOT_TOKEN}"
fi

if [[ -z "$YOURATTO_DISCORD_BOT_TOKEN" || -z "$YOURATTO_DISCORD_GUILD_ID" ]]; then
  echo "STOP: need YOURATTO_DISCORD_BOT_TOKEN + YOURATTO_DISCORD_GUILD_ID" >&2
  echo "See briefs/2026-07-23_discord-ops-g0-setup.md" >&2
  exit 1
fi
# Discord bot tokens are ~59–100+ chars (three base64-ish segments). App/Client/Guild IDs are ~17–19.
if [[ ${#YOURATTO_DISCORD_BOT_TOKEN} -lt 50 ]]; then
  echo "STOP: token looks too short (${#YOURATTO_DISCORD_BOT_TOKEN} chars)." >&2
  echo "You probably pasted Application ID / Client ID / Guild ID." >&2
  echo "Portal → your app → Bot → Reset Token → Copy (long string with dots)." >&2
  exit 1
fi
OSINT_DISCORD_GUILD_ID="${OSINT_DISCORD_GUILD_ID:-$YOURATTO_DISCORD_GUILD_ID}"
OSINT_DISCORD_BOT_TOKEN="${OSINT_DISCORD_BOT_TOKEN:-$YOURATTO_DISCORD_BOT_TOKEN}"

# Persist secrets: ~/.cemini/discord-ops.env (0600) + thin source hook in ~/.zprofile
mkdir -p "$HOME/.cemini"
ENV_FILE="$HOME/.cemini/discord-ops.env"
umask 077
cat >"$ENV_FILE" <<EOF
# Generated by setup_discord_ops_macos.sh — never commit
export YOURATTO_DISCORD_BOT_TOKEN='${YOURATTO_DISCORD_BOT_TOKEN//\'/\'\\\'\'}'
export YOURATTO_DISCORD_GUILD_ID='$YOURATTO_DISCORD_GUILD_ID'
export OSINT_DISCORD_BOT_TOKEN='${OSINT_DISCORD_BOT_TOKEN//\'/\'\\\'\'}'
export OSINT_DISCORD_GUILD_ID='$OSINT_DISCORD_GUILD_ID'
export DISCORD_OPS_TOKEN_ENV='YOURATTO_DISCORD_BOT_TOKEN'
export DISCORD_OPS_DRY_RUN='true'
EOF
chmod 600 "$ENV_FILE"
echo "Wrote $ENV_FILE (mode 600)"

ZPROFILE="$HOME/.zprofile"
BLOCK_START="# >>> cemini-discord-ops >>>"
BLOCK_END="# <<< cemini-discord-ops <<<"
SNIPPET=$(cat <<EOF
$BLOCK_START
[ -f "\$HOME/.cemini/discord-ops.env" ] && . "\$HOME/.cemini/discord-ops.env"
$BLOCK_END
EOF
)
if [[ -f "$ZPROFILE" ]] && grep -q "$BLOCK_START" "$ZPROFILE"; then
  tmp="$(mktemp)"
  awk -v s="$BLOCK_START" -v e="$BLOCK_END" '
    $0==s {skip=1; next}
    $0==e {skip=0; next}
    !skip {print}
  ' "$ZPROFILE" >"$tmp"
  cat "$tmp" >"$ZPROFILE"
  rm -f "$tmp"
fi
{
  echo ""
  echo "$SNIPPET"
} >>"$ZPROFILE"
echo "Updated $ZPROFILE to source discord-ops.env (restart Cursor)."

# shellcheck disable=SC1090
. "$ENV_FILE"

# --- ~/.discord-ops.json merge via python ---
python3 - <<'PY'
import json, os
from pathlib import Path

home = Path.home() / ".discord-ops.json"
cfg = {"projects": {}, "default_project": "youratto"}
if home.exists():
    try:
        cfg = json.loads(home.read_text())
    except Exception:
        pass
cfg.setdefault("projects", {})

def project(guild_id, token_env):
    return {
        "guild_id": guild_id,
        "token_env": token_env,
        "tool_profile": "channels",
        "tool_profile_add": [
            "create_webhook", "delete_webhook", "edit_webhook", "execute_webhook",
            "get_webhook", "list_webhooks", "health_check", "list_guilds", "get_guild",
            "assign_role", "list_members", "list_roles", "create_invite", "get_invites",
            "send_message",
        ],
        "channels": {},
    }

cfg["projects"]["youratto"] = project(
    os.environ["YOURATTO_DISCORD_GUILD_ID"], "YOURATTO_DISCORD_BOT_TOKEN"
)
cfg["projects"]["osint"] = project(
    os.environ["OSINT_DISCORD_GUILD_ID"], "OSINT_DISCORD_BOT_TOKEN"
)
cfg["default_project"] = "youratto"
home.write_text(json.dumps(cfg, indent=2) + "\n")
print(f"Wrote {home}")
PY

# Per-project pointers
mkdir -p "$ATTO_ROOT" "$OSINT_ROOT"
echo '{"project":"youratto"}' >"$ATTO_ROOT/.discord-ops.json"
echo '{"project":"osint"}' >"$OSINT_ROOT/.discord-ops.json"
echo "Wrote project pointers .discord-ops.json"

# Merge discord-ops into Cursor project mcp.json via wrapper (Cursor GUI
# does not inherit ~/.zprofile — wrapper sources ~/.cemini/discord-ops.env).
merge_mcp() {
  local mcp="$1"
  local wrapper="$2"
  python3 - "$mcp" "$wrapper" <<'PY'
import json, sys
from pathlib import Path
path = Path(sys.argv[1])
wrapper = sys.argv[2]
data = {"mcpServers": {}}
if path.exists():
    data = json.loads(path.read_text())
data.setdefault("mcpServers", {})
data["mcpServers"]["discord-ops"] = {
    "command": wrapper,
    "args": [],
    "env": {"DISCORD_OPS_DRY_RUN": "true"},
}
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text(json.dumps(data, indent=2) + "\n")
print(f"Merged discord-ops (wrapper) into {path}")
PY
}

merge_mcp "$ATTO_ROOT/.cursor/mcp.json" "$ATTO_ROOT/scripts/discord_ops_mcp.sh"
merge_mcp "$OSINT_ROOT/.cursor/mcp.json" "$OSINT_ROOT/scripts/discord_ops_mcp.sh"

echo ""
echo "Running discord-ops health from atto dir (dry-run env)…"
(
  cd "$ATTO_ROOT"
  npx -y discord-ops@latest health
) || {
  echo "Health failed — check intents (Server Members + Message Content ON) and bot invite."
  echo "Invite (Manage Channels + Manage Webhooks + Send Messages + …):"
  echo "  Developer Portal → OAuth2 → URL Generator → bot scope"
  exit 1
}

echo ""
echo "G0 COMPLETE."
echo "  1. Quit + reopen Cursor (inherit ~/.zprofile env)."
echo "  2. Settings → MCP → enable discord-ops → Retry."
echo "  3. Agent skill: youratto-discord-ops / discord-ops"
echo "  4. Keep DISCORD_OPS_DRY_RUN=true until you say LIVE OK."
echo "Canon: TipDrop discord-ops — not Claude Code Discord Channels plugin."
