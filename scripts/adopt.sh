#!/usr/bin/env bash
# Unified adopt runner — replaces per-wave adopt_k*_phase*.sh entrypoints.
#
#   bash scripts/adopt.sh --list
#   bash scripts/adopt.sh k254              # phase0 then phase1 if present
#   bash scripts/adopt.sh k254 phase0
#   bash scripts/adopt.sh --manifest        # refresh wiki/osint/meta/adopt-manifest.yaml
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MANIFEST="$ROOT/wiki/osint/meta/adopt-manifest.yaml"

list_waves() {
  find "$ROOT/scripts" -maxdepth 1 -name 'adopt_k*_phase0.sh' -o -name 'adopt_k*_phase1.sh' | \
    xargs -n1 basename | sed -E 's/^adopt_(k[0-9]+(_[0-9]+)?)_.*/\1/' | sort -u
}

write_manifest() {
  echo "# Adopt wave manifest — generated by scripts/adopt.sh --manifest"
  echo "version: 1"
  echo "updated: $(date +%Y-%m-%d)"
  echo "root: $ROOT"
  echo "waves:"
  for wave in $(list_waves); do
    echo "  - id: $wave"
    for phase in phase0 phase1; do
      f="$ROOT/scripts/adopt_${wave}_${phase}.sh"
      if [[ -f "$f" ]]; then
        echo "    ${phase}: scripts/adopt_${wave}_${phase}.sh"
      fi
    done
  done
}

run_wave() {
  local wave="$1"
  local phase="${2:-all}"
  local ran=0
  local waves_dir="$ROOT/scripts/adopt-waves"
  run_script() {
    local script="$1"
    [[ -f "$script" ]] || return 0
    echo "=== RUN $(basename "$script") ==="
    bash "$script"
    ran=1
  }
  if [[ "$phase" == "all" || "$phase" == "phase0" ]]; then
    run_script "$waves_dir/adopt_${wave}_phase0.sh"
  fi
  if [[ "$phase" == "all" || "$phase" == "phase1" ]]; then
    run_script "$waves_dir/adopt_${wave}_phase1.sh"
  fi
  if [[ "$ran" -eq 0 ]]; then
    echo "No adopt script found for wave=$wave phase=$phase" >&2
    exit 1
  fi
}

case "${1:-}" in
  --list) list_waves ;;
  --manifest)
    write_manifest > "$MANIFEST"
    echo "Wrote $MANIFEST"
    ;;
  -h|--help) sed -n '2,8p' "$0" ;;
  *)
    [[ -n "${1:-}" ]] || { echo "Usage: adopt.sh --list | --manifest | <wave> [phase0|phase1|all]" >&2; exit 1; }
    run_wave "$1" "${2:-all}"
    ;;
esac
